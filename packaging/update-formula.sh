#!/bin/sh
# Write the Homebrew formula (basert.rb) for a release.
#
#   packaging/update-formula.sh <version> <bundles-dir> <out-dir>
#
# <bundles-dir> holds the release's .sha256 files (the tarballs themselves are
# not needed). The formula is written whole from the template below rather
# than patched, so a release only ever changes the version and the two
# checksums, and the diff in the tap repo says exactly that. publish.yml opens
# that diff as a PR on the tap (basecompute/homebrew-tap, Formula/basert.rb).
set -eu

[ $# -eq 3 ] || { echo "usage: $0 <version> <bundles-dir> <out-dir>" >&2; exit 2; }
version=$1
dir=$2
out=$3

sha() {
  f="$dir/$1-$version.tar.gz.sha256"
  [ -f "$f" ] || { echo "missing $f" >&2; exit 1; }
  s=$(cut -d' ' -f1 "$f")
  printf '%s' "$s" | grep -Eq '^[0-9a-f]{64}$' || { echo "bad checksum in $f" >&2; exit 1; }
  printf '%s' "$s"
}
mac_sha=$(sha basert-engine-macos-arm64)
linux_sha=$(sha basert-engine-linux-arm64-cuda)
base="https://github.com/basecompute/baseRT/releases/download/v$version"

mkdir -p "$out"
cat > "$out/basert.rb" <<EOF
# Generated by the BaseRT release pipeline and rewritten on each release.
# Don't edit by hand; changes here are overwritten.
class Basert < Formula
  desc "Fast local LLM inference on Apple Silicon and NVIDIA GB10"
  homepage "https://docs.basecompute.co"
  version "$version"
  # The basert CLI launcher is Apache-2.0; the engine binaries it drives are
  # under the proprietary BaseRT Engine license shipped in the bundle.
  license :cannot_represent

  depends_on arch: :arm64

  # One prebuilt bundle per OS, both arm64 only. (The url sits under a CPU
  # check because Homebrew's style rules don't allow it directly in
  # on_macos / on_linux; this is the layout GoReleaser-generated taps use.)
  on_macos do
    depends_on macos: :sequoia
    if Hardware::CPU.arm?
      url "$base/basert-engine-macos-arm64-$version.tar.gz"
      sha256 "$mac_sha"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "$base/basert-engine-linux-arm64-cuda-$version.tar.gz"
      sha256 "$linux_sha"
    end
  end

  def install
    # Keep the release layout intact in libexec: the launcher finds the
    # basert-* runtime tools next to itself, and they find their kernel files
    # the same way. bin/basert is a small script that runs libexec/basert.
    libexec.install Dir["*"]
    # basert self update leaves this copy to Homebrew and names the command.
    (libexec/"installed-by").write "Homebrew: brew upgrade basert\n"
    bin.write_exec_script libexec/"basert"
    # For the Rust / Python / Node bindings and C API users.
    lib.install_symlink Dir[libexec/"libbaseRT*"]
    include.install_symlink libexec/"include/baseRT"
  end

  def caveats
    on_linux do
      <<~EOS
        The Linux engine runs on NVIDIA GPUs (GB10 / DGX Spark) and needs the
        NVIDIA driver and the CUDA 13 runtime (libcublas) on this machine.
      EOS
    end
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/basert --version")
  end
end
EOF
echo "$out/basert.rb -> $version"
