#!/bin/sh
# Write the Homebrew formula (basert.rb) for a release.
#
#   packaging/update-formula.sh <version> <bundles-dir> <out-dir>
#
# <bundles-dir> holds the release's .sha256 files (the tarballs themselves are
# not needed). The formula is written whole from the template below rather
# than patched, so a release only ever changes the version and the checksums,
# and the diff in the tap repo says exactly that. publish.yml opens that diff
# as a PR on the tap (basecompute/homebrew-tap, Formula/basert.rb).
#
# The macOS and Linux arm64 (CUDA) bundles are in every release. The Linux
# x86-64 (ROCm) one is optional: the engine's release pipeline ships a release
# without it when its AMD runner is off, and then the formula stays arm64-only.
set -eu

[ $# -eq 3 ] || { echo "usage: $0 <version> <bundles-dir> <out-dir>" >&2; exit 2; }
version=$1
dir=$2
out=$3

sha() {
  f="$dir/$1-$version.tar.gz.sha256"
  [ -f "$f" ] || { echo "missing $f" >&2; exit 1; }
  s=$(cut -d' ' -f1 "$f")
  printf '%s' "$s" | grep -Eq '^[0-9a-f]{64}$' || { echo "bad checksum in $f" >&2; exit 1; }
  printf '%s' "$s"
}
mac_sha=$(sha basert-engine-macos-arm64)
linux_sha=$(sha basert-engine-linux-arm64-cuda)
rocm_sha=""
if [ -f "$dir/basert-engine-linux-x64-rocm-$version.tar.gz.sha256" ]; then
  rocm_sha=$(sha basert-engine-linux-x64-rocm)
fi
base="https://github.com/basecompute/baseRT/releases/download/v$version"

if [ -n "$rocm_sha" ]; then
  desc="Fast local LLM inference on Apple Silicon, NVIDIA GB10 and AMD Strix"
  layout="  # One prebuilt bundle per platform: Apple Silicon on macOS, and on Linux
  # arm64 (NVIDIA CUDA) and x86-64 (AMD ROCm)."
  linux_arch=""
  rocm_url="
    if Hardware::CPU.intel?
      url \"$base/basert-engine-linux-x64-rocm-$version.tar.gz\"
      sha256 \"$rocm_sha\"
    end"
  caveats="if Hardware::CPU.arm?
        <<~EOS
          The Linux arm64 engine runs on NVIDIA GPUs (GB10 / DGX Spark) and needs
          the NVIDIA driver and the CUDA 13 runtime (libcublas) on this machine.
        EOS
      else
        <<~EOS
          The Linux x86-64 engine runs on AMD Strix Halo (gfx1151) and Strix Point
          (gfx1150) GPUs and needs the ROCm 10 runtime in /opt/rocm/core-10.0:
            sudo apt install amdrocm-blas10.0-gfx1151   # Strix Halo
            sudo apt install amdrocm-blas10.0-gfx1150   # Strix Point
        EOS
      end"
else
  desc="Fast local LLM inference on Apple Silicon and NVIDIA GB10"
  layout="  # One prebuilt bundle per OS, both arm64 only."
  linux_arch="
    depends_on arch: :arm64"
  rocm_url=""
  caveats="<<~EOS
        The Linux engine runs on NVIDIA GPUs (GB10 / DGX Spark) and needs the
        NVIDIA driver and the CUDA 13 runtime (libcublas) on this machine.
      EOS"
fi

mkdir -p "$out"
cat > "$out/basert.rb" <<EOF
# Generated by the BaseRT release pipeline and rewritten on each release.
# Don't edit by hand; changes here are overwritten.
class Basert < Formula
  desc "$desc"
  homepage "https://docs.basecompute.co"
  version "$version"
  # The basert CLI launcher is Apache-2.0; the engine binaries it drives are
  # under the proprietary BaseRT Engine license shipped in the bundle.
  license :cannot_represent

$layout (Each url sits under a CPU check
  # because Homebrew's style rules don't allow it directly in on_macos /
  # on_linux; this is the layout GoReleaser-generated taps use.)
  on_macos do
    depends_on arch: :arm64
    depends_on macos: :sequoia
    if Hardware::CPU.arm?
      url "$base/basert-engine-macos-arm64-$version.tar.gz"
      sha256 "$mac_sha"
    end
  end

  on_linux do$linux_arch
    if Hardware::CPU.arm?
      url "$base/basert-engine-linux-arm64-cuda-$version.tar.gz"
      sha256 "$linux_sha"
    end$rocm_url
  end

  def install
    # Keep the release layout intact in libexec: the launcher finds the
    # basert-* runtime tools next to itself, and they find their kernel files
    # the same way. bin/basert is a small script that runs libexec/basert.
    libexec.install Dir["*"]
    # basert self update leaves this copy to Homebrew and names the command.
    (libexec/"installed-by").write "Homebrew: brew upgrade basert\n"
    bin.write_exec_script libexec/"basert"
    # For the Rust / Python / Node bindings and C API users.
    lib.install_symlink Dir[libexec/"libbaseRT*"]
    include.install_symlink libexec/"include/baseRT"
  end

  def caveats
    on_linux do
      $caveats
    end
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/basert --version")
  end
end
EOF
echo "$out/basert.rb -> $version${rocm_sha:+ (with the Linux x86-64 ROCm bundle)}"
